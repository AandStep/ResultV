package com.resultv.android.vpn

/**
 * Сколько раз подряд самотест CA может ответить «не знаю», прежде чем
 * браузерный ad-block будет оставлен выключенным до следующего подключения.
 */
const val CERT_SELF_TEST_MAX_ATTEMPTS = 3

/**
 * Пауза перед следующей попыткой самотеста после INCONCLUSIVE, или null,
 * когда попытки исчерпаны. [attemptsDone] — сколько попыток уже сделано.
 *
 * INCONCLUSIVE — это «не знаю», а не «не доверен»: зонд идёт через свежий
 * туннель к удалённому серверу, и на первом подключении после установки APK
 * конкурирует с фоновой загрузкой фильтр-листов, так что тайм-аут там —
 * норма, а не приговор сертификату. Одна попытка поэтому и превращала
 * занятую сеть в молча выключенную на всю сессию функцию.
 *
 * Паузы растут, потому что ждать приходится именно окончания этой загрузки:
 * первая — на случай короткой заминки, вторая — на случай, что листы ещё
 * качаются. Ждать бесконечно нельзя, каждая попытка занимает worker
 * сервиса, за которым стоит очередь reload-ов.
 */
fun certSelfTestRetryDelayMs(attemptsDone: Int): Long? = when {
    attemptsDone >= CERT_SELF_TEST_MAX_ATTEMPTS -> null
    attemptsDone <= 1 -> 5_000L
    else -> 15_000L
}
