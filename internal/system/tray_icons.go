// Atlases are generated by scripts/gen-tray-icons.mjs.
//
//go:embed trayicons/atlas.txt trayicons/atlas_*.png
var trayIconFS embed.FS

const (
	trayIconAuto  = "auto"
	trayIconGlobe = "globe"
	trayIconBlank = "blank"

	trayAtlasColumns = 16
)

var trayAtlasSizes = []int{16, 20, 24, 28, 32, 40, 48}

var (
	trayAtlasOnce  sync.Once
	trayAtlasIndex map[string]int

	trayAtlasMu     sync.Mutex
	trayAtlasImages = map[int]image.Image{}
)

func trayAtlasCell(name string) (int, bool) {
	trayAtlasOnce.Do(func() {
		trayAtlasIndex = map[string]int{}
		data, err := trayIconFS.ReadFile("trayicons/atlas.txt")
		if err != nil {
			return
		}
		for i, line := range strings.Split(strings.TrimSpace(string(data)), "\n") {
			trayAtlasIndex[strings.TrimSpace(line)] = i
		}
	})
	i, ok := trayAtlasIndex[name]
	return i, ok
}

// trayHasIcon reports whether the atlas has a cell for name.
func trayHasIcon(name string) bool {
	_, ok := trayAtlasCell(name)
	return ok
}

func trayAtlas(size int) (image.Image, error) {
	trayAtlasMu.Lock()
	defer trayAtlasMu.Unlock()
	if img, ok := trayAtlasImages[size]; ok {
		return img, nil
	}
	data, err := trayIconFS.ReadFile(fmt.Sprintf("trayicons/atlas_%d.png", size))
	if err != nil {
		return nil, err
	}
	img, err := png.Decode(bytes.NewReader(data))
	if err != nil {
		return nil, err
	}
	trayAtlasImages[size] = img
	return img, nil
}

// trayIconImage returns the icon as a size×size image. A size the atlases do
// not cover gets the largest smaller cell, centred.
func trayIconImage(name string, size int) (*image.NRGBA, error) {
	out := image.NewNRGBA(image.Rect(0, 0, size, size))
	if name == trayIconBlank {
		return out, nil
	}
	idx, ok := trayAtlasCell(name)
	if !ok {
		return nil, fmt.Errorf("tray icon %q not in atlas", name)
	}
	cell := trayAtlasSizes[0]
	for _, s := range trayAtlasSizes {
		if s <= size {
			cell = s
		}
	}
	atlas, err := trayAtlas(cell)
	if err != nil {
		return nil, err
	}
	src := image.Pt((idx%trayAtlasColumns)*cell, (idx/trayAtlasColumns)*cell)
	off := (size - cell) / 2
	draw.Draw(out, image.Rect(off, off, off+cell, off+cell), atlas, src, draw.Src)
	return out, nil
}

type trayMark int

const (
	trayMarkNone trayMark = iota
	trayMarkSelected
	trayMarkConnected
)

var (
	trayMarkRing      = [3]uint8{0x1f, 0x1f, 0x1f}
	trayMarkConnColor = [3]uint8{0x00, 0xa8, 0x19}
	trayMarkSelColor  = [3]uint8{0xb4, 0xb8, 0xbc}
)

// drawTrayMark puts a status dot with a dark ring into the bottom-right
// corner of img, antialiased by 4×4 supersampling.
func drawTrayMark(img *image.NRGBA, mark trayMark) {
	if mark == trayMarkNone {
		return
	}
	fill := trayMarkConnColor
	if mark == trayMarkSelected {
		fill = trayMarkSelColor
	}
	size := float64(img.Rect.Dx())
	outer := size * 0.27
	ring := size / 16
	cx, cy := size-outer, size-outer
	for y := int(cy - outer); y < img.Rect.Dy(); y++ {
		for x := int(cx - outer); x < img.Rect.Dx(); x++ {
			var inRing, inDot float64
			for sy := 0; sy < 4; sy++ {
				for sx := 0; sx < 4; sx++ {
					dx := float64(x) + (float64(sx)+0.5)/4 - cx
					dy := float64(y) + (float64(sy)+0.5)/4 - cy
					d := dx*dx + dy*dy
					if d <= (outer-ring)*(outer-ring) {
						inDot++
					} else if d <= outer*outer {
						inRing++
					}
				}
			}
			cover := (inRing + inDot) / 16
			if cover == 0 {
				continue
			}
			var c [3]float64
			for i := 0; i < 3; i++ {
				c[i] = (float64(trayMarkRing[i])*inRing + float64(fill[i])*inDot) / (inRing + inDot)
			}
			o := img.PixOffset(x, y)
			p := img.Pix[o : o+4]
			srcA := float64(p[3]) / 255
			outA := cover + srcA*(1-cover)
			for i := 0; i < 3; i++ {
				p[i] = uint8((c[i]*cover + float64(p[i])*srcA*(1-cover)) / outA)
			}
			p[3] = uint8(outA*255 + 0.5)
		}
	}
}

// pixelUpscale stretches img to size×size by repeating pixels.
func pixelUpscale(img *image.NRGBA, size int) *image.NRGBA {
	sw, sh := img.Rect.Dx(), img.Rect.Dy()
	out := image.NewNRGBA(image.Rect(0, 0, size, size))
	for y := 0; y < size; y++ {
		sy := y * sh / size
		for x := 0; x < size; x++ {
			sx := x * sw / size
			copy(out.Pix[out.PixOffset(x, y):out.PixOffset(x, y)+4], img.Pix[img.PixOffset(sx, sy):img.PixOffset(sx, sy)+4])
		}
	}
	return out
}

func encodeTrayPNG(img image.Image) ([]byte, error) {
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// encodeICO wraps one PNG-compressed image into an .ico container.
func encodeICO(img image.Image) ([]byte, error) {
	data, err := encodeTrayPNG(img)
	if err != nil {
		return nil, err
	}
	w, h := img.Bounds().Dx(), img.Bounds().Dy()
	var buf bytes.Buffer
	_ = binary.Write(&buf, binary.LittleEndian, [3]uint16{0, 1, 1})
	buf.Write([]byte{byte(w), byte(h), 0, 0})
	_ = binary.Write(&buf, binary.LittleEndian, [2]uint16{1, 32})
	_ = binary.Write(&buf, binary.LittleEndian, [2]uint32{uint32(len(data)), 6 + 16})
	buf.Write(data)
	return buf.Bytes(), nil
}

var (
	trayMenuIconMu    sync.Mutex
	trayMenuIconCache = map[string][]byte{}
)

// trayMenuIcon returns the bytes MenuItem.SetIcon expects, or nil.
func trayMenuIcon(name string, mark trayMark) []byte {
	key := fmt.Sprintf("%s/%d", name, mark)
	trayMenuIconMu.Lock()
	defer trayMenuIconMu.Unlock()
	if data, ok := trayMenuIconCache[key]; ok {
		return data
	}
	data, err := buildTrayMenuIcon(name, mark)
	if err != nil {
		data = nil
	}
	trayMenuIconCache[key] = data
	return data
}
